/** The same quote all day, a different one each day (and for each slot). */
export function quoteOfDay(list: Quote[], date: string, slot = 0) {
  const seed = [...date].reduce((sum, char) => sum + char.charCodeAt(0), 0) + Number(date.slice(8, 10)) * 7
  return list[(seed + slot) % list.length]
}
