/** A quote as one line, for a notification: ﴿…﴾ for a verse, «…» for the Prophet's words. */
export const quoteLine = (quote: Quote) =>
  quote.kind === 'quran' ? `﴿${quote.text.replace(/\n/g, ' ')}﴾ [${quote.source}]` : `${quote.lead ? `${quote.lead} ` : ''}«${quote.text}» (${quote.source})`

